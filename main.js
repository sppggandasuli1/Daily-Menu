// ========================================
// FORMAT DATE
// ========================================

function formatDate(date) {

    const options = {
        day: "numeric",
        month: "long",
        year: "numeric"
    };

    return date.toLocaleDateString(
        "id-ID",
        options
    );
}


// ========================================
// GET DATE KEY
// ========================================

function getDateKey(date) {

    const year =
        date.getFullYear();

    const month =
        String(
            date.getMonth() + 1
        ).padStart(2, "0");

    const day =
        String(
            date.getDate()
        ).padStart(2, "0");

    return `${year}-${month}-${day}`;
}


// ========================================
// DISPLAY MENU
