// ========================================
// CREATE DATE LIST FOR ONE MONTH
// ========================================

function createDateList() {

    dateList.innerHTML = "";


    // September 2026
    const year = 2026;

    // JavaScript months start from 0
    // January = 0
    // September = 8
    const month = 8;


    // Get number of days in September
    const numberOfDays =
        new Date(
            year,
            month + 1,
            0
        ).getDate();


    // Create button for every day
    for (
        let dayNumber = 1;
        dayNumber <= numberOfDays;
        dayNumber++
    ) {

        const date =
            new Date(
                year,
                month,
                dayNumber
            );


        // Create date key
        const dateKey =
            `${year}-${String(month + 1).padStart(2, "0")}-${String(dayNumber).padStart(2, "0")}`;


        // Create button
        const button =
            document.createElement("button");


        button.className =
            "date-item";


        // Day name
        const day =
            date.toLocaleDateString(
                "id-ID",
                {
                    weekday: "short"
                }
            );


        // Month name
        const monthName =
            date.toLocaleDateString(
                "id-ID",
                {
                    month: "short"
                }
            );


        // Button content
        button.innerHTML = `
            <span class="day">${day}</span>
            <span class="date">${dayNumber}</span>
            <span class="month">${monthName}</span>
        `;


        // Save date
        button.dataset.date =
            dateKey;


        // =================================
        // CLICK DATE
        // =================================

        button.addEventListener(
            "click",
            function() {

                currentDate =
                    new Date(
                        dateKey +
                        "T00:00:00"
                    );

                displayMenu();

            }
        );


        // Add button to date list
        dateList.appendChild(button);

    }


    // Update active date
    updateActiveDate();
}


// ========================================
// UPDATE ACTIVE DATE
// ========================================

function updateActiveDate() {

    const currentKey =
        getDateKey(currentDate);


    const buttons =
        document.querySelectorAll(
            ".date-item"
        );


    buttons.forEach(function(button) {

        if (
            button.dataset.date ===
            currentKey
        ) {

            button.classList.add(
                "active"
            );

        } else {

            button.classList.remove(
                "active"
            );

        }

    });
}


